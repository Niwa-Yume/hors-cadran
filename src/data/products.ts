export type CategoryId = 'cards' | 'caps' | 'leather' | 'valet' | 'boxes' | 'paper';
export type ProductStatus = 'available' | 'sold_out' | 'one_of_one';

export interface Category {
  id: CategoryId;
  label: string;
  /** Category accent colour. */
  accent: string;
  /** Text colour that reads on the accent. */
  onAccent: string;
}

export interface ProductSpec {
  reference: string;
  calibre: string;
  case: string;
  powerReserve: string;
  waterResistance: string;
  provenance: string;
  year: number;
  condition: string;
  edition: string;
}

export interface Product {
  id: string;
  title: string;
  maison: string;
  category: CategoryId;
  priceCHF: number;
  status: ProductStatus;
  isNew: boolean;
  accent: string;
  images: string[];
  spec: ProductSpec;
}

export interface Drop {
  id: string;
  number: string;
  title: string;
  productId: string;
  pieces: number;
  city: string;
  image: string;
  alt: string;
}

